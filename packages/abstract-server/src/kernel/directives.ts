import type { MapStage } from "@mapward/core";

/**
 * Директивы глазами двух фич: карта собирает по их файлам статус и этапы объекта, директивы
 * берут текст дефолтного этапа. Знание одно — где лежит и что по
 * умолчанию, — поэтому оно здесь, а не в одной из фич.
 */

/**
 * Дефолт инструмента — два этапа, и он намеренно бедный: свой порядок работы с агентом карта
 * описывает сама, файлами в `_directives.workflow/` (решение 0017). Три прежних режима сюда
 * не переехали — проверка и сухой прогон были двумя именами одного.
 *
 * Карта кладёт его этапы в модель объекта, у которого своих нет, а директивы берут отсюда текст
 * этапа — файла у дефолтного нет.
 */
export const DEFAULT_WORKFLOW: (MapStage & { text: string })[] = [
  {
    name: "Обсудить",
    order: 10,
    marksDone: false,
    path: "",
    text: [
      "Прочитай директиву и скажи, что о ней думаешь: как понял, что сделаешь, где придётся",
      "решать за человека. Задай уточняющие вопросы.",
      "",
      "Файлы не трогай.",
    ].join("\n"),
  },
  {
    name: "Выполнить",
    order: 20,
    marksDone: true,
    path: "",
    text: [
      "Выполни директиву.",
      "",
      "Перед началом закоммить точечно файлы, которые будешь править, — тогда результат",
      "виден диффом, а откат делается git restore по конкретным путям.",
      "Результат не коммить: его смотрит человек.",
    ].join("\n"),
  },
];

/** Описания дефолтных этапов без текстов: их кладёт в модель чтение карты. */
export const defaultStages = (): MapStage[] =>
  DEFAULT_WORKFLOW.map(({ name, order, marksDone, path }) => ({ name, order, marksDone, path }));

/** Текст дефолтного этапа: у него нет файла, поэтому промпт лежит рядом с описанием. */
export const defaultStageText = (name: string): string =>
  DEFAULT_WORKFLOW.find((stage) => stage.name === name)?.text ?? "";
