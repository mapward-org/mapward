import type { DirectiveMode, MapObject } from "@mapward/core";

/**
 * Prompts are the whole interface to the agent, so they live in pure-model: they can be read
 * without an editor, and the rules they carry come from decision 0002.
 */
export function objectPrompt(object: MapObject, mapPath: string): string {
  return [
    `Работаем с объектом карты mapward «${object.name}».`,
    `Карта: ${mapPath}. Объект: ${object.path} (${object.address}).`,
    "",
    "Правки лучше делать через директивы: положи текст в _directives и выполни его,",
    "тогда сделанное останется записанным, а не только в этом разговоре.",
  ].join("\n");
}

/**
 * Three buttons, three prompts. `check` reads, `dry-run` plans, `run` acts — and only the
 * last one is allowed to touch files, so a mistake in the wording costs nothing until then.
 */
export function directivePrompt(
  mode: DirectiveMode,
  directivePath: string,
  object: MapObject,
  mapPath: string,
): string {
  const head = [
    `Директива: ${directivePath}`,
    `Объект карты: «${object.name}», ${object.path} (${object.address}).`,
    `Карта: ${mapPath}.`,
    "",
    // Решение 0016: без этих строк агент шёл сканировать репозиторий и собирал заново то,
    // что карта уже знает. Промпт — весь интерфейс к нему, и про MCP он молчал.
    "Карту читай через MCP mapward, а не обходом репозитория.",
    "",
    'Первым делом позови read_docs { section: "mcp" } — там все параметры чтения и что',
    "чем достаётся. Этот промпт их не перечисляет намеренно: пересказ отстаёт от инструмента,",
    "и то, чего в пересказе нет, просто не используют. Считай, что здесь сказано меньше, чем",
    "умеет MCP, и список вопросов к нему бери оттуда, а не отсюда.",
    "",
    "Дальше начни с обзора — read_object по этому объекту с глубиной и без метрик, — а потом",
    "бери нужное поимённо. Как именно, сказано в той же доке; там же про остальные разделы:",
    "устройство объекта, адресацию, метрики, директивы.",
    "",
    "В код иди по ссылкам из метрик, когда нужно содержимое файлов. Сканировать проект",
    "целиком не нужно. Метрика при этом отвечает, где лежит код, а не где внутри него нужная",
    "строка: искать её — обычным поиском по указанному месту.",
    // Строки «MCP не подключён — читай файлы» здесь больше нет: она приезжала всегда, в том
    // числе при живом MCP, и отменяла первый шаг — агент шёл читать файлы, как ему и
    // «разрешили». Отсутствие инструментов видно и без подсказки, а путь карты назван выше.
    "",
  ];

  const tail = {
    check: [
      "Прочитай директиву и проверь её, ничего не меняя:",
      "— понятно ли, что нужно сделать, нет ли противоречий с решениями карты;",
      "— существуют ли файлы и адреса, на которые она ссылается;",
      "— что осталось недосказанным и о чём стоит спросить.",
      "",
      "Сам текст директивы и экшонов бери из карты по имени, а не файлом с диска.",
      "Прежде чем идти на диск за чем угодно, посмотри список метрик объекта и его родителей:",
      "то, чем карта себя описывает, она же и отдаёт — одним вызовом вместо десятка чтений.",
      "Ссылка не разрешилась — посмотри в git, когда именно цель исчезла: директива, написанная",
      "до переезда, протухла, а не ошибочна, и это разные выводы.",
      "",
      "Ответь текстом, файлы не трогай.",
    ],
    "dry-run": [
      "Прочитай директиву и расскажи, что именно сделаешь: какие файлы создашь,",
      "какие изменишь и что в них появится. Файлы не трогай — это сухой прогон.",
      "Отдельно назови места, где придётся решать за человека.",
    ],
    run: [
      "Выполни директиву.",
      "",
      "Перед началом закоммить точечно файлы, которые будешь править, — тогда результат",
      "виден диффом, а откат делается git restore по конкретным путям.",
      "Результат не коммить: его смотрит человек.",
      "",
      "Когда закончишь, запиши состояние рядом с директивой:",
      "_directives.state/<имя директивы>.state.json вида",
      '{ "directive": "<полная копия текста директивы>", "status": "done", "ran": "<время>" }.',
      "Копия нужна, чтобы потом было видно, менялась ли директива после выполнения.",
    ],
  }[mode];

  return [...head, ...tail].join("\n");
}
