import type { MapObject, MapStage } from "@mapward/core";

/**
 * Prompts are the whole interface to the agent, so they live in pure-model: they can be read
 * without an editor, and the rules they carry come from decision 0002.
 */

/**
 * Голова, общая для всех промптов: карту читать через MCP и оттуда же брать устройство
 * инструмента. Одна на объектный промпт и на промпт этапа, потому что забывший её терминал
 * ведёт себя ровно так, как описано в решении 0016, — уходит обходить репозиторий.
 */
const MCP_HEAD = [
  "Карту читай через MCP mapward, а не обходом репозитория.",
  "",
  'Первым делом позови read_docs { section: "mcp" } — там все параметры чтения и что',
  "чем достаётся. Этот промпт их не перечисляет намеренно: пересказ отстаёт от инструмента,",
  "и то, чего в пересказе нет, просто не используют. Считай, что здесь сказано меньше, чем",
  "умеет MCP, и список вопросов к нему бери оттуда, а не отсюда.",
  "",
  'Как устроены директивы — read_docs { section: "directives" }: этапы, состояние прогона,',
  "экшоны. Там же остальные разделы: устройство объекта, адресация, метрики.",
  "",
  "Дальше начни с обзора этого объекта, а потом бери нужное поимённо. Как зовётся обзор,",
  "написано там же, в разделе mcp, и написано целиком. Здесь его нет намеренно: вызов,",
  "переписанный сюда наполовину, зовут именно в таком виде, а за второй половиной не идут.",
  "",
  "В код иди по ссылкам из метрик, когда нужно содержимое файлов. Сканировать проект",
  "целиком не нужно. Метрика при этом отвечает, где лежит код, а не где внутри него нужная",
  "строка: искать её — обычным поиском по указанному месту.",
  "",
  "Сам текст директивы, экшона и этапа бери из карты по имени, а не файлом с диска.",
  "",
  "Что уже прочитано в этом разговоре — доки, обзор, память, — повторно не читай: оно у тебя",
  "в контексте. Этап часто приходит в разговор, который уже разогрелся.",
];

const stageList = (object: MapObject) =>
  object.workflow.map((stage) => `«${stage.name}»`).join(", ");

/**
 * Блок с промптом объекта — решение 0018. Отбит так же, как хук этапа, и по той же причине:
 * разбирая, почему агент повёл себя так, человек должен видеть, где кончился инструмент и
 * началась его карта.
 */
const fromMap = (object: MapObject) =>
  object.prompt ? ["", "--- От карты ---", "", object.prompt] : [];

/**
 * Промпт терминала на объекте. Терминал заводится на объект, а не на директиву (решение 0017),
 * поэтому именно здесь человек и агент узнают, как директива запускается: кнопок больше нет.
 *
 * Инструмент назван вызовом, а не прозой: решение 0016 показало, что применяется показанное.
 */
export function objectPrompt(object: MapObject, mapPath: string): string {
  return [
    `Работаем с объектом карты mapward «${object.name}».`,
    `Карта: ${mapPath}. Объект: ${object.path} (${object.address}).`,
    "",
    ...MCP_HEAD,
    "",
    "Правки лучше делать через директивы: положи текст в _directives и выполни его,",
    "тогда сделанное останется записанным, а не только в этом разговоре.",
    "",
    `Директива выполняется по этапам — у этого объекта они такие: ${stageList(object)}.`,
    "Запускают её словами: «выполни этап такой-то по директиве такой-то». Промпт этапа",
    "бери из карты, а не из этого разговора:",
    "",
    '  run_directive { address: "<адрес объекта>", directive: "<имя файла>", stage: "<этап>" }',
    "",
    "Вызов вернёт текст этапа и отметит, что прогон начался. Закончив, позови",
    "finish_directive с теми же параметрами — состояние карта пишет сама, во frontmatter",
    "директивы, руками его не правят.",
    ...fromMap(object),
  ].join("\n");
}

/**
 * Разогрев агента директивы: пока автор пишет директиву, агент собирает то, что нужно любому
 * этапу, — и первый этап не тратит на это минуты. Только карта и сама директива: код зависит от
 * текста, который ещё меняется, и прочитанный заранее оказался бы не тем.
 */
const warmUp = (object: MapObject, directive: string) => [
  "",
  "--- Разогрев ---",
  "",
  "Сейчас этапа нет: автор работает с директивой, а ты готовишься, чтобы первый этап",
  "начался сразу. Сделай то, что выше велено сделать первым делом: доки mcp и directives,",
  "обзор объекта, индекс памяти. Прочитай текст своей директивы:",
  "",
  `  read_index { address: "${object.address}", file: "${directive}" }`,
  "",
  "Код не читай: какой понадобится, станет ясно на этапе, по готовому тексту. Директиву не",
  "правь и этап не запускай. Закончив, ответь одним словом «готов» и жди.",
];

/**
 * Промпт агента директивы. Рядом с директивой живёт свой разговор, и агент должен с первой
 * строки знать, чей он: иначе на «выполни реализацию» он ищет директиву по имени. Вызов этапа
 * показан целиком, с адресом и именем, — применяется показанное (решение 0016).
 *
 * С разогревом — новый разговор, открытый без этапа. Без него — разговор, который заводит кнопка
 * этапа: фраза этапа едет следом, и готовиться отдельно незачем.
 */
export function directivePrompt(params: {
  object: MapObject;
  mapPath: string;
  directive: string;
  directivePath: string;
  warmUp: boolean;
}): string {
  const { object, mapPath, directive, directivePath } = params;
  const call =
    `  run_directive { address: "${object.address}", directive: "${directive}", ` +
    'stage: "<этап>" }';
  return [
    `Ты агент директивы ${directive} на объекте карты mapward «${object.name}».`,
    `Директива: ${directivePath}.`,
    `Карта: ${mapPath}. Объект: ${object.path} (${object.address}).`,
    "",
    ...MCP_HEAD,
    "",
    `Директива выполняется по этапам — у этого объекта они такие: ${stageList(object)}.`,
    "Автор запускает их словами: «выполни этап такой-то». Промпт этапа бери из карты:",
    "",
    call,
    "",
    "Вызов вернёт текст этапа и отметит, что прогон начался. Закончив, позови",
    "finish_directive с теми же параметрами — состояние карта пишет сама, во frontmatter",
    "директивы, руками его не правят.",
    ...fromMap(object),
    ...(params.warmUp ? warmUp(object, directive) : []),
  ].join("\n");
}

/**
 * Фраза, которую кнопка отправляет в живую сессию объекта. Это не промпт: содержательного в ней
 * нет, и агент, получив её, идёт за промптом этапа в MCP — ровно как если бы человек набрал то
 * же самое руками (решение 0017).
 *
 * Живёт она здесь, рядом с промптами, а не в кнопке: имя инструмента и его параметры должны
 * знать в одном месте, иначе второй экземпляр контракта разойдётся с первым (решение 0016).
 */
export const stageRequest = (params: { object: MapObject; directive: string; stage: string }) =>
  `Выполни этап «${params.stage}» по директиве ${params.directive} ` +
  `на объекте ${params.object.address}`;

/**
 * Промпт этапа: голова про MCP одна на все этапы, дальше промпт объекта, текст самого
 * этапа и хук прогонов.
 *
 * Промпт объекта стоит до этапа: это правила объекта, а не довесок к нему, и верны они
 * одинаково в терминале и в прогоне — решение 0018.
 *
 * Хук — сквозное правило, заданное в `_index.json` один раз: приклеивается к любому этапу,
 * не переписывая их по отдельности (решение 0017).
 */
export function stagePrompt(params: {
  stage: MapStage;
  text: string;
  hook?: string;
  directivePath: string;
  object: MapObject;
  mapPath: string;
}): string {
  const { stage, text, hook, directivePath, object, mapPath } = params;

  const head = [
    `Этап «${stage.name}» по директиве: ${directivePath}`,
    `Объект карты: «${object.name}», ${object.path} (${object.address}).`,
    `Карта: ${mapPath}.`,
    "",
    ...MCP_HEAD,
    ...fromMap(object),
    "",
    "--- Этап ---",
    "",
  ];

  const tail = [
    "",
    "--- Как закончить ---",
    "",
    "Позови finish_directive с тем же объектом, директивой и этапом. Состояние прогона",
    "пишет карта во frontmatter директивы — статус, этап, счётчик кругов, руками их не правят.",
    stage.marksDone
      ? "Этот этап помечает директиву выполненной, поэтому зови его, только если она правда выполнена."
      : "Этот этап выполнения не помечает: директива останется незакрытой, и это правильно.",
  ];

  return [...head, text, ...(hook ? ["", "--- Кроме того ---", "", hook] : []), ...tail].join("\n");
}

/**
 * Отпечаток промпта этапа — решение 0039: по нему агент говорит, что текст у него уже есть, и
 * сервер не шлёт его заново. Это сравнение, а не защита, поэтому FNV-1a, без зависимостей.
 * Считается по собранному промпту целиком: поменялись пути, общее правило объекта или сам
 * этап — отпечаток другой, и текст приедет.
 */
export function promptFingerprint(prompt: string): string {
  let hash = 0x81_1c_9d_c5;
  for (let at = 0; at < prompt.length; at++) {
    hash ^= prompt.charCodeAt(at);
    hash = Math.imul(hash, 0x01_00_01_93);
  }
  return (hash >>> 0).toString(16).padStart(8, "0");
}
