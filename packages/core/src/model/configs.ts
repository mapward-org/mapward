/**
 * Конфиги карты как типы: `_index.json`, `config.json` метрики и экшона. Они едут по мосту в
 * объекте и в протокол плагина, поэтому живут здесь. Схемы, которыми сервер проверяет файлы,
 * лежат у него (`features/map/domain/schema.ts`) — клиенту и плагину проверять файлы нечего.
 */

/**
 * Группа метрик — решение 0025: вкладка объекта со своим набором метрик.
 *
 * Группа живёт у объекта, а не у метрики: у неё есть описание, порядок и своя раскладка, а
 * метрике из `shared-metrics` положить их некуда — она достаётся многим объектам сразу.
 */
export type MetricGroup = {
  key: string;
  /** Подпись вкладки; без неё вкладка подписана ключом. */
  label?: string;
  /** Что это за набор — markdown над сеткой. */
  description?: string;
  /** Ключи метрик. Метрика, не названная ни в одной группе, не показывается и не собирается. */
  metrics: string[];
  /**
   * Раскладка вкладки — компонент `.tsx`: путь от папки того `_index.json`, где она написана,
   * или адрес `mapward://…` файла. Без неё метрики идут вертикальным списком, по одной на
   * строку, в порядке `metrics`.
   */
  layout?: string;
  /**
   * Эта вкладка — превью объекта: её показывает карточка, которой группу не назвали. Отдельного
   * описания у превью нет — карточка берёт у вкладки метрики и раскладку.
   */
  defaultPreview?: boolean;
};

export type MetricGroups = {
  /** Мерджить унаследованные группы по ключу или заменить их целиком — как у воркфлоу. */
  mode?: "merge" | "replace";
  groups: MetricGroup[];
};

/** `_index.json` as decision 0003 describes it. Everything is optional: any field may be inherited. */
export type ObjectIndex = {
  name?: string;
  props?: Record<string, unknown>;
  extends?: string;
  /**
   * Решение 0018: то, что карта говорит своему терминалу поверх сказанного инструментом.
   * Доезжает до промпта терминала и до промпта этапа: правило объекта не зависит от того,
   * запущена директива или нет.
   */
  prompt?: string;
  /**
   * Решение 0017: чем этапы объекта отличаются от унаследованных и что примешивается
   * к промпту любого из них. Сами этапы — файлы в `_directives.workflow/`.
   */
  "directives-workflow"?: { mode?: "merge" | "replace"; prompt?: string };
  /**
   * Решение 0025: вкладки объекта. Заданы — метрики вне групп не показываются и не собираются:
   * так унаследованную метрику можно не использовать, не отказываясь от прототипа.
   */
  "metric-groups"?: MetricGroups;
};

/**
 * `config.json` метрики. Метрика — компонент, который сам берёт данные у плагинов; готовые виды
 * (список, дерево, ссылка, …) — компоненты встроенного плагина `views`.
 *
 * Платформа знает только свои поля; лишние проверка схемы пропускает, а мердж и подстановки
 * проходят по ним как по любым — но не читает их никто: настройки компонента — `params`.
 */
export type MetricConfig = {
  label?: string;
  extends?: string;
  /**
   * Путь от папки того `config.json`, где написан. Без него метрике нечем рисоваться: так бывает
   * только у слоя, который ждёт `component` от прототипа.
   */
  component?: string;
  /** Настройки компонента: проходят подстановку, как весь конфиг, и приходят ему пропсом. */
  params?: Record<string, unknown>;
  /**
   * Что видит агент: метод плагина с параметрами. Не обязателен, но без него агенту остаются
   * только методы плагина.
   */
  agent?: { plugin: string; method: string; params?: unknown };
  [field: string]: unknown;
};

/**
 * Поле формы экшона — решение 0038. Названия взяты у ручного запуска GitHub Actions
 * (`workflow_dispatch.inputs`): формат свой, но тот, который агент и человек уже видели.
 */
export type ActionInput = {
  type?: "string" | "boolean" | "number" | "choice";
  description?: string;
  required?: boolean;
  /** Проходит подстановку, как весь конфиг: умолчание берут из свойств объекта. */
  default?: string | number | boolean;
  /** Варианты для `choice`. */
  options?: string[];
  /** Многострочное поле для `string`: промпту часто нужен абзац, а не слово. */
  multiline?: boolean;
};

/**
 * Экшон `config.json` — кнопка с формой над изменяющим методом плагина: `plugin`, `method`,
 * `params`. Путь `plugin` — от папки этого `config.json`, как у метрики. Форма — параметры метода
 * по его JSON-схеме из самоописания плагина, кроме заданных в `params`.
 */
export type ActionConfig = {
  label?: string;
  description?: string;
  extends?: string;
  /**
   * `true` — открыть форму, даже когда она заполнена целиком. Текст — вопрос в отдельном окне перед
   * запуском, с данными формы через `${{ inputs.<имя> }}`: «Удалить ${{ inputs.path }}?».
   */
  confirm?: boolean | string;
  /** Папка плагина: от этого `config.json` или абсолютная. */
  plugin?: string;
  /** Изменяющий метод плагина, который зовёт кнопка. */
  method?: string;
  /** Заданные параметры метода: проходят подстановку и в форму не попадают. */
  params?: Record<string, unknown>;
  /**
   * Своя форма — `.tsx` от папки этого `config.json`, как компонент метрики. Получает
   * `{ params, schema, submit }` и рисует поля сама; без него форма — по схеме метода.
   */
  component?: string;
  /** Поля формы явно — форма вместо схемы метода; данные её приходят методу полем `inputs`. */
  inputs?: Record<string, ActionInput>;
};
