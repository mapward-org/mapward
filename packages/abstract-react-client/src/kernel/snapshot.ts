/**
 * Режим снимка — страница плагина `screenshot`: тот же клиент, но то, что человек видит у себя,
 * можно перекрыть на один снимок, ничего у него не меняя.
 *
 * - `viewState` — значения `useViewState` по ключу: раскрытые папки, свёрнутость и т.п.;
 * - `expand: "all"` — всё раскрыто, ничего не свёрнуто: ключ, у которого вызов назвал своё
 *   `expanded`, отдаёт его (если `viewState` не перекрыл ключ явно);
 * - `params` — параметры снимаемой метрики поверх её `config.json`, слиянием по ключу.
 *
 * Запись состояния вида на такой странице — только в её память: снимок не трогает настройки
 * человека.
 */
export type Snapshot = {
  viewState?: Record<string, unknown>;
  expand?: "all";
  params?: Record<string, unknown>;
};
